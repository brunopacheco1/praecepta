package io.github.brunopacheco1.praecepta.tck;

import java.util.Comparator;
import java.util.EnumMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.function.Function;
import java.util.function.Predicate;
import java.util.stream.Collectors;

import io.github.brunopacheco1.praecepta.tck.Feature.Area;
import io.github.brunopacheco1.praecepta.tck.TckRunner.Outcome;
import io.github.brunopacheco1.praecepta.tck.TckRunner.Status;
import io.github.brunopacheco1.praecepta.tck.TckSuite.Check;

/**
 * Renders RESULTS.md: the totals of the whole kit, by compliance level, feature area, release, feature and model, and
 * the decision-table checks counted since 0.1, by test case.
 */
final class TckResults {

    /**
     * @param area the node's feature area: the latest layer of the plan whose features its content uses
     */
    record Result(Check check, Outcome outcome, Area area) {

        Status status() {
            return outcome.status();
        }
    }

    /** How many reasons a model's row lists before it says there are more. */
    private static final int REASONS_PER_MODEL = 3;

    private TckResults() {
    }

    /** @param byCase every node's result, by TCK test case in name order */
    static String render(Map<String, List<Result>> byCase) {
        var results = byCase.values().stream().flatMap(List::stream).toList();
        var tables = new LinkedHashMap<String, List<Result>>();
        byCase.forEach((testCase, caseResults) -> {
            var checks = caseResults.stream().filter(result -> result.check().isDecisionTable()).toList();
            if (!checks.isEmpty()) {
                tables.put(testCase, checks);
            }
        });
        var tableResults = tables.values().stream().flatMap(List::stream).toList();

        var md = new StringBuilder();
        appendIntroduction(md, results, tableResults);
        appendLevels(md, byCase);
        appendAreas(md, results);
        appendReleases(md, results);
        appendFeatures(md, results);
        appendModels(md, byCase);
        appendFailures(md, results, "### Failures");
        appendDecisionTables(md, tableResults);
        appendTestCases(md, tables);
        appendNotSupported(md, tableResults);
        appendFailures(md, tableResults, "### Decision-table failures");
        return md.toString();
    }

    private static void appendIntroduction(StringBuilder md, List<Result> results, List<Result> tables) {
        int passed = count(results, Status.PASSED);
        int evaluated = passed + count(results, Status.FAILED);
        int tablesPassed = count(tables, Status.PASSED);
        md.append("""
                <!--
                SPDX-FileCopyrightText: Bruno Pacheco

                SPDX-License-Identifier: Apache-2.0
                -->

                # DMN TCK results

                Praecepta against the [DMN Technology Compatibility Kit](https://github.com/dmn-tck/tck) (TCK), every
                model of compliance levels 2 and 3 at commit
                [`%s`](https://github.com/dmn-tck/tck/tree/%s). This file is generated by `TckTest`, with the
                baseline of passing result nodes (`baseline.txt`); regenerate both, deliberately, with:

                ```
                mvn -pl praecepta-tck -am test -Dtck.update=true
                ```

                A *result node* is one expected result in a TCK test file: a decision (or a decision service or business
                knowledge model) evaluated with one test case's inputs. It *passes* when Praecepta gives the expected
                result (or reports an error where the kit expects one), *fails* when it gives another, and is *not
                supported* when it needs a feature Praecepta does not have yet, named below with the release of the
                [DMN 1.5 plan](https://github.com/brunopacheco1/praecepta/issues/120) that brings it. The build fails
                only on a regression: a node the baseline lists that no longer passes. Semantics are judged by DMN 1.5
                and the TCK alone; where both leave a case open, what Praecepta does is recorded in
                [DMN conformance](../docs/DMN-CONFORMANCE.md).

                **The whole kit: %s of %s result nodes pass (%s).** Of the %s that Praecepta evaluates, %s pass (%s).

                **Decision tables: %d of %d checks pass (%s).**

                ## The whole kit

                Praecepta evaluates a decision through its model's decision requirement graph, which computes the
                decisions it requires, where `DmnReader.readModel` reads the model: decision tables, and literal
                expressions in the FEEL subset output entries compute (arithmetic of numbers, strings, dates, times
                and durations). In another model it evaluates a decision on its own, a decision table with
                `DmnReader` and the engine, and a literal expression as an output expression. Everything else is not
                supported yet. A test file's result nodes that are commented out are not counted.

                | Compliance level | Models | Result nodes | Passed | Failed | Not supported |
                |---|---:|---:|---:|---:|---:|
                """.formatted(TckSuite.TCK_COMMIT.substring(0, 7), TckSuite.TCK_COMMIT,
                number(passed), number(results.size()), percent(passed, results.size()), number(evaluated), number(passed),
                percent(passed, evaluated), tablesPassed, tables.size(), percent(tablesPassed, tables.size())));
    }

    /** One row per compliance level, and the total. */
    private static void appendLevels(StringBuilder md, Map<String, List<Result>> byCase) {
        for (int level = 2; level <= 3; level++) {
            var prefix = "compliance-level-" + level + "/";
            var cases = byCase.entrySet().stream().filter(entry -> entry.getKey().startsWith(prefix)).toList();
            var results = cases.stream().flatMap(entry -> entry.getValue().stream()).toList();
            line(md, "| %d | %d | %s |".formatted(level, cases.size(), counts(results)));
        }
        var results = byCase.values().stream().flatMap(List::stream).toList();
        line(md, "| **Total** | **%d** | **%s** |".formatted(byCase.size(), counts(results).replace(" | ", "** | **")));
    }

    /** One row per feature area, in release order. */
    private static void appendAreas(StringBuilder md, List<Result> results) {
        md.append("""

                ### By feature area

                A node's feature area is the latest layer of the plan whose features its content uses: its decision's
                logic and that of the decisions and knowledge models it requires, whether Praecepta reads them or not.
                It does not change as Praecepta grows, so each row shows how far that layer is done.

                | Feature area | Release | Result nodes | Passed | Failed | Not supported |
                |---|---|---:|---:|---:|---:|
                """);
        for (var area : Area.values()) {
            var areaResults = results.stream().filter(result -> result.area() == area).toList();
            line(md, "| %s | %s | %s |".formatted(area.title(), release(area), counts(areaResults)));
        }
    }

    /** The unsupported nodes by the latest release among what they need: what each release would complete. */
    private static void appendReleases(StringBuilder md, List<Result> results) {
        var unsupported = results.stream().filter(result -> result.status() == Status.UNSUPPORTED).toList();
        if (unsupported.isEmpty()) {
            return;
        }
        md.append("""

                ### What each release unlocks

                The not-supported nodes by the latest release among the features they need: if each release brings its
                features, these nodes have all they need once it ships.

                | Release | Feature area | Not-supported nodes | Evaluated by then, of all nodes |
                |---|---|---:|---:|
                """);
        var byRelease = new EnumMap<Area, Integer>(Area.class);
        unsupported.forEach(result -> byRelease.merge(latest(result.outcome().needs()), 1, Integer::sum));
        int supported = results.size() - unsupported.size();
        for (var area : Area.values()) {
            int unlocked = byRelease.getOrDefault(area, 0);
            if (area == Area.DECISION_TABLES && unlocked == 0) {
                continue; // what Praecepta has: only a gap in its decision tables would be counted here
            }
            supported += unlocked;
            line(md, "| %s | %s | %s | %s (%s) |".formatted(release(area), area.title(), number(unlocked), number(supported),
                    percent(supported, results.size())));
        }
    }

    /** Every feature the unsupported nodes need, by area and then by the number of nodes that need it. */
    private static void appendFeatures(StringBuilder md, List<Result> results) {
        var unsupported = results.stream().filter(result -> result.status() == Status.UNSUPPORTED).toList();
        if (unsupported.isEmpty()) {
            return;
        }
        md.append("""

                ### Not supported, by feature

                Every feature the not-supported nodes need. *Needed by* counts the nodes that need it, whatever else
                they need; *stops* counts those it is the first missing feature of (so these add up to the
                not-supported nodes); *alone* counts those that need nothing else.

                | Feature | Release | Needed by | Stops | Alone |
                |---|---|---:|---:|---:|
                """);
        var needed = new LinkedHashMap<Feature, int[]>();
        for (var result : unsupported) {
            var needs = result.outcome().needs();
            for (var feature : needs) {
                var counts = needed.computeIfAbsent(feature, f -> new int[3]);
                counts[0]++;
                if (feature.equals(needs.getFirst())) {
                    counts[1]++;
                }
                if (needs.size() == 1) {
                    counts[2]++;
                }
            }
        }
        needed.entrySet().stream()
                .sorted(Comparator.comparing((Map.Entry<Feature, int[]> entry) -> entry.getKey().area())
                        .thenComparing(entry -> -entry.getValue()[0])
                        .thenComparing(entry -> entry.getKey().name()))
                .forEach(entry -> line(md, "| %s | %s | %d | %d | %d |".formatted(escape(entry.getKey().name()),
                        release(entry.getKey().area()), entry.getValue()[0], entry.getValue()[1], entry.getValue()[2])));
    }

    /** One row per model: its counts, and what its unsupported nodes need most. */
    private static void appendModels(StringBuilder md, Map<String, List<Result>> byCase) {
        md.append("""

                ### By model

                | TCK test case | Result nodes | Passed | Failed | Not supported | Most needed |
                |---|---:|---:|---:|---:|---|
                """);
        byCase.forEach((testCase, caseResults) -> line(md, "| %s | %s | %s |".formatted(link(testCase), counts(caseResults),
                escape(mostNeeded(caseResults)))));
    }

    /** The features a model's unsupported nodes need most, most first. */
    private static String mostNeeded(List<Result> results) {
        var needed = new LinkedHashMap<String, Integer>();
        results.stream().filter(result -> result.status() == Status.UNSUPPORTED)
                .forEach(result -> result.outcome().needs().forEach(feature -> needed.merge(feature.label(), 1, Integer::sum)));
        var sorted = needed.entrySet().stream()
                .sorted(Map.Entry.<String, Integer>comparingByValue().reversed().thenComparing(Map.Entry.comparingByKey()))
                .map(Map.Entry::getKey)
                .toList();
        var shown = String.join("; ", sorted.subList(0, Math.min(REASONS_PER_MODEL, sorted.size())));
        return sorted.size() > REASONS_PER_MODEL ? shown + "; …" : shown;
    }

    /** The failed nodes, by test case and label, with what differed. */
    private static void appendFailures(StringBuilder md, List<Result> results, String heading) {
        var failures = results.stream()
                .filter(result -> result.status() == Status.FAILED)
                .sorted(Comparator.comparing((Result result) -> result.check().testCase()).thenComparing(result -> result.check().label()))
                .toList();
        if (failures.isEmpty()) {
            return;
        }
        md.append('\n').append(heading).append("\n\n");
        failures.forEach(result -> line(md, "- `%s/%s`: %s".formatted(
                result.check().testCase(), result.check().label(), escape(result.outcome().detail()))));
    }

    // ---- the decision-table checks ----------------------------------------------------------------

    private static void appendDecisionTables(StringBuilder md, List<Result> results) {
        int passed = count(results, Status.PASSED);
        int failed = count(results, Status.FAILED);
        int unsupported = count(results, Status.UNSUPPORTED);
        md.append("""

                ## Decision tables

                The checks counted since Praecepta's first release: the result nodes of decisions whose logic is a
                decision table. A check is *not supported* when the table uses a feature Praecepta does not have (the
                DMN reader rejects it), or the inputs are of a kind it does not take.

                **%d of %d checks pass (%s).** Of the %d checks Praecepta supports, %d pass (%s).

                | Outcome | Checks |
                |---|---:|
                | Passed | %d |
                | Failed | %d |
                | Not supported | %d |

                ### By test case

                | TCK test case | Passed | Failed | Not supported | Not supported because |
                |---|---:|---:|---:|---|
                """.formatted(passed, results.size(), percent(passed, results.size()), passed + failed, passed,
                percent(passed, passed + failed), passed, failed, unsupported));
    }

    /** One row per TCK test case: its counts and why its unsupported checks are not supported. */
    private static void appendTestCases(StringBuilder md, Map<String, List<Result>> byCase) {
        byCase.forEach((testCase, caseResults) -> {
            var reasons = caseResults.stream()
                    .filter(result -> result.status() == Status.UNSUPPORTED)
                    .map(result -> result.outcome().detail())
                    .distinct()
                    .sorted()
                    .collect(Collectors.joining("; "));
            line(md, "| %s | %d | %d | %d | %s |".formatted(link(testCase), count(caseResults, Status.PASSED),
                    count(caseResults, Status.FAILED), count(caseResults, Status.UNSUPPORTED), escape(reasons)));
        });
    }

    /** The missing features, most needed first. */
    private static void appendNotSupported(StringBuilder md, List<Result> results) {
        var missing = results.stream().filter(result -> result.status() == Status.UNSUPPORTED).toList();
        if (missing.isEmpty()) {
            return;
        }
        md.append("""

                ### Decision tables not supported

                What the unsupported checks need, by number of checks:

                | Feature | Checks |
                |---|---:|
                """);
        tally(missing, result -> result.outcome().detail()).entrySet().stream()
                .sorted(Map.Entry.<String, Integer>comparingByValue().reversed().thenComparing(Map.Entry.comparingByKey()))
                .forEach(entry -> line(md, "| %s | %d |".formatted(escape(entry.getKey()), entry.getValue())));
    }

    // ---- helpers ----------------------------------------------------------------------------------

    /** The latest area among a node's needs: the release after which it has all it needs. */
    static Area latest(List<Feature> needs) {
        return needs.stream().map(Feature::area).reduce(Area.DECISION_TABLES, Area::max);
    }

    /** {@code nodes | passed | failed | not supported}, with thousands separated. */
    private static String counts(List<Result> results) {
        return "%s | %s | %s | %s".formatted(number(results.size()), number(count(results, Status.PASSED)),
                number(count(results, Status.FAILED)), number(count(results, Status.UNSUPPORTED)));
    }

    private static String release(Area area) {
        return area.issue() == 0 ? area.release()
                : "%s ([#%d](https://github.com/brunopacheco1/praecepta/issues/%d))".formatted(area.release(), area.issue(), area.issue());
    }

    private static String link(String testCase) {
        return "[%s](https://github.com/dmn-tck/tck/tree/%s/TestCases/%s)".formatted(testCase, TckSuite.TCK_COMMIT, testCase);
    }

    /** Appends a line ending in {@code \n} on every platform, so RESULTS.md is the same everywhere. */
    private static void line(StringBuilder md, String text) {
        md.append(text).append('\n');
    }

    private static int count(List<Result> results, Status status) {
        return (int) results.stream().filter(byStatus(status)).count();
    }

    private static Predicate<Result> byStatus(Status status) {
        return result -> result.status() == status;
    }

    private static <K> Map<K, Integer> tally(List<Result> results, Function<Result, K> key) {
        var counts = new LinkedHashMap<K, Integer>();
        results.forEach(result -> counts.merge(key.apply(result), 1, Integer::sum));
        return counts;
    }

    /** A count with a comma between thousands, as the rest of the documentation writes them: {@code 3,385}. */
    static String number(int value) {
        return String.format(Locale.ROOT, "%,d", value);
    }

    private static String percent(int part, int whole) {
        return whole == 0 ? "n/a" : String.format(Locale.ROOT, "%.1f %%", 100.0 * part / whole);
    }

    private static String escape(String text) {
        return text.replace("|", "\\|").replace("\n", " ");
    }
}
