package io.github.brunopacheco1.praecepta.tck;

import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.TreeMap;
import java.util.function.Function;
import java.util.stream.Collectors;

import io.github.brunopacheco1.praecepta.tck.TckRunner.Outcome;
import io.github.brunopacheco1.praecepta.tck.TckRunner.Status;
import io.github.brunopacheco1.praecepta.tck.TckSuite.Check;

/** Renders RESULTS.md: the pass rate, results per TCK test case, missing features and failures. */
final class TckResults {

    record Result(Check check, Outcome outcome) {
    }

    private TckResults() {
    }

    static String render(List<Result> results) {
        var total = results.size();
        var counts = count(results, result -> result.outcome().status());
        int passed = counts.getOrDefault(Status.PASSED, 0);
        int failed = counts.getOrDefault(Status.FAILED, 0);
        int unsupported = counts.getOrDefault(Status.UNSUPPORTED, 0);

        var md = new StringBuilder();
        md.append("""
                <!--
                SPDX-FileCopyrightText: Bruno Pacheco

                SPDX-License-Identifier: Apache-2.0
                -->

                # DMN TCK results

                Praecepta against the decision-table test cases of the
                [DMN Technology Compatibility Kit](https://github.com/dmn-tck/tck), at commit
                [`%s`](https://github.com/dmn-tck/tck/tree/%s). This file is generated by `TckTest`, which
                fails when it is out of date; regenerate it with:

                ```
                mvn -pl praecepta-tck -am test -Dtck.update=true
                ```

                A *check* is one expected result in a TCK test file: a decision table evaluated with one test
                case's inputs. Only decisions whose logic is a decision table count; other decisions in the
                same models (literal expressions, contexts, invocations) are outside Praecepta's scope. A check
                is *not supported* when the table uses a feature Praecepta does not have (the DMN reader
                rejects it), or the inputs are of a kind it does not take.

                **%d of %d checks pass (%s).** Of the %d checks Praecepta supports, %d pass (%s).

                | Outcome | Checks |
                |---|---:|
                | Passed | %d |
                | Failed | %d |
                | Not supported | %d |

                ## By test case

                | TCK test case | Passed | Failed | Not supported | Not supported because |
                |---|---:|---:|---:|---|
                """.formatted(TckSuite.TCK_COMMIT.substring(0, 7), TckSuite.TCK_COMMIT,
                passed, total, percent(passed, total), passed + failed, passed, percent(passed, passed + failed),
                passed, failed, unsupported));

        var byCase = results.stream().collect(Collectors.groupingBy(result -> result.check().testCase(), TreeMap::new, Collectors.toList()));
        byCase.forEach((testCase, caseResults) -> {
            var caseCounts = count(caseResults, result -> result.outcome().status());
            var reasons = caseResults.stream()
                    .filter(result -> result.outcome().status() == Status.UNSUPPORTED)
                    .map(result -> result.outcome().detail())
                    .distinct()
                    .sorted()
                    .collect(Collectors.joining("; "));
            md.append("| [%s](https://github.com/dmn-tck/tck/tree/%s/TestCases/%s) | %d | %d | %d | %s |\n".formatted(
                    testCase, TckSuite.TCK_COMMIT, testCase,
                    caseCounts.getOrDefault(Status.PASSED, 0), caseCounts.getOrDefault(Status.FAILED, 0),
                    caseCounts.getOrDefault(Status.UNSUPPORTED, 0), escape(reasons)));
        });

        var missing = results.stream()
                .filter(result -> result.outcome().status() == Status.UNSUPPORTED)
                .toList();
        if (!missing.isEmpty()) {
            md.append("\n## Not supported\n\nWhat the unsupported checks need, by number of checks:\n\n| Feature | Checks |\n|---|---:|\n");
            count(missing, result -> result.outcome().detail()).entrySet().stream()
                    .sorted(Map.Entry.<String, Integer>comparingByValue().reversed().thenComparing(Map.Entry.comparingByKey()))
                    .forEach(entry -> md.append("| %s | %d |\n".formatted(escape(entry.getKey()), entry.getValue())));
        }

        var failures = results.stream()
                .filter(result -> result.outcome().status() == Status.FAILED)
                .sorted(Comparator.comparing((Result result) -> result.check().testCase()).thenComparing(result -> result.check().label()))
                .toList();
        if (!failures.isEmpty()) {
            md.append("\n## Failures\n\n");
            failures.forEach(result -> md.append("- `%s/%s`: %s\n".formatted(
                    result.check().testCase(), result.check().label(), escape(result.outcome().detail()))));
        }
        return md.toString();
    }

    private static <K> Map<K, Integer> count(List<Result> results, Function<Result, K> key) {
        var counts = new LinkedHashMap<K, Integer>();
        results.forEach(result -> counts.merge(key.apply(result), 1, Integer::sum));
        return counts;
    }

    private static String percent(int part, int whole) {
        return whole == 0 ? "n/a" : String.format(Locale.ROOT, "%.1f %%", 100.0 * part / whole);
    }

    private static String escape(String text) {
        return text.replace("|", "\\|").replace("\n", " ");
    }
}
