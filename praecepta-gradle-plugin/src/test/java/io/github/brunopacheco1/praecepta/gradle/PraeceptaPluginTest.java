package io.github.brunopacheco1.praecepta.gradle;

import java.io.IOException;
import java.net.URISyntaxException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

import org.assertj.core.api.Assertions;
import org.gradle.api.GradleException;
import org.gradle.api.InvalidUserDataException;
import org.gradle.api.Project;
import org.gradle.api.Task;
import org.gradle.api.tasks.SourceSetContainer;
import org.gradle.testfixtures.ProjectBuilder;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/**
 * The plugin in an in-process Gradle project: the extension, the task and its wiring into the {@code main} source
 * set, and what the task writes and reports. Real builds (the plugin resolved by id, caching, the configuration
 * cache, other Gradle versions) are in {@link PraeceptaPluginFunctionalTest}.
 */
class PraeceptaPluginTest {

    @TempDir
    Path projectDir;

    private Project project;

    private PraeceptaExtension extension;

    @BeforeEach
    void project() throws IOException, URISyntaxException {
        var rules = Files.createDirectories(projectDir.resolve("src/main/rules"));
        for (var name : List.of("fees.csv", "overlapping.csv", "discount.csv", "nationalities.csv", "camunda-modeler-discount.dmn",
                "credit.dmn")) {
            Files.copy(Path.of(PraeceptaPluginTest.class.getResource("/tables/" + name).toURI()), rules.resolve(name));
        }
        project = ProjectBuilder.builder().withProjectDir(projectDir.toFile()).build();
        project.getPluginManager().apply("java");
        project.getPluginManager().apply(PraeceptaPlugin.ID);
        extension = project.getExtensions().getByType(PraeceptaExtension.class);
        extension.getPackageName().set("com.acme.rules");
    }

    @Test
    void writes_sources_and_dmn_where_the_main_source_set_finds_them() {
        fees("fees");
        extension.getFileHeader().set("SPDX-FileCopyrightText: Acme");

        task().generate();

        var sources = projectDir.resolve("build/generated/sources/praecepta/java/main/com/acme/rules");
        var resources = projectDir.resolve("build/generated/resources/praecepta/main/com/acme/rules");
        Assertions.assertThat(sources.resolve("Fees.java")).content()
                .startsWith("// SPDX-FileCopyrightText: Acme\n// Generated by praecepta-gradle-plugin from fees.csv. Do not edit.\n");
        Assertions.assertThat(sources.resolve("FeesInput.java")).exists();
        Assertions.assertThat(sources.resolve("FeesOutput.java")).exists();
        Assertions.assertThat(resources.resolve("Fees.dmn")).content().contains("aggregation=\"SUM\"");

        var main = project.getExtensions().getByType(SourceSetContainer.class).getByName("main");
        Assertions.assertThat(main.getJava().getSrcDirs())
                .contains(project.file("build/generated/sources/praecepta/java/main"));
        Assertions.assertThat(main.getResources().getSrcDirs())
                .contains(project.file("build/generated/resources/praecepta/main"));
    }

    @Test
    void generates_the_maven_plugin_golden_files_but_for_the_tool_they_name() throws IOException {
        // the compiler's golden tables: fees in a package with a two-line header, discount in the default package
        fees("fees");
        extension.getFileHeader().set("Golden test header\nsecond line");
        extension.getTables().getByName("fees").getInputs().getColumns().getFirst().getAllowedValues().set("\"islands\",\"mainland\"");
        task().generate();
        Assertions.assertThat(generated(projectDir.resolve("build/generated"), "com/acme/rules/", "Fees"))
                .isEqualTo(golden("fees"));

        var discountProject = ProjectBuilder.builder().withProjectDir(projectDir.resolve("discount").toFile()).build();
        discountProject.getPluginManager().apply(PraeceptaPlugin.class);
        var discount = discountProject.getExtensions().getByType(PraeceptaExtension.class);
        discount.getPackageName().set("");
        discount.getTables().register("discount", table -> {
            table.getSource().set(projectDir.resolve("src/main/rules/discount.csv").toFile());
            table.getClassName().set("Discount");
            table.getHitPolicy().set("FIRST");
            table.inputs(inputs -> {
                inputs.column("country", column -> column.getAllowedValues().set("\"PT\",\"ES\",\"FR\""));
                inputs.column("age", column -> {
                    column.getType().set("NUMBER");
                    column.getAllowedValues().set("[0..120]");
                });
                inputs.column("since", column -> column.getType().set("DATE"));
            });
            table.outputs(outputs -> {
                outputs.column("discount", column -> column.getType().set("NUMBER"));
                outputs.column("tier");
            });
        });
        ((GeneratePraecepta) discountProject.getTasks().getByName(PraeceptaPlugin.TASK_NAME)).generate();
        Assertions.assertThat(generated(projectDir.resolve("discount/build/generated"), "", "Discount"))
                .isEqualTo(golden("discount"));
    }

    @Test
    void compile_java_and_process_resources_depend_on_the_task() {
        var compileJava = project.getTasks().getByName("compileJava");
        var processResources = project.getTasks().getByName("processResources");
        var generate = project.getTasks().getByName(PraeceptaPlugin.TASK_NAME);
        Assertions.assertThat(List.<Task>copyOf(compileJava.getTaskDependencies().getDependencies(compileJava))).contains(generate);
        Assertions.assertThat(List.<Task>copyOf(processResources.getTaskDependencies().getDependencies(processResources))).contains(generate);
    }

    @Test
    void columns_keep_the_order_they_are_declared_in_and_take_every_setting() {
        extension.tables(tables -> tables.register("offers", table -> {
            table.getSource().set(projectDir.resolve("src/main/rules/nationalities.csv").toFile());
            table.getClassName().set("Offer");
            table.getHitPolicy().set("first");
            table.inputs(inputs -> {
                inputs.column("nationalities", column -> {
                    column.getList().set(true);
                    column.getAllowedValues().set("\"PT\",\"ES\",\"BR\"");
                });
                inputs.column("ages", column -> {
                    column.getType().set("number");
                    column.getList().set(true);
                });
            });
            table.outputs(outputs -> outputs.column("offer", column -> column.getPriority().set(List.of("iberian", "senior", "standard"))));
        }));

        task().generate();

        var sources = projectDir.resolve("build/generated/sources/praecepta/java/main/com/acme/rules");
        Assertions.assertThat(sources.resolve("OfferInput.java")).content()
                .contains("public record OfferInput(java.util.List<String> nationalities, java.util.List<java.math.BigDecimal> ages)");
        Assertions.assertThat(projectDir.resolve("build/generated/resources/praecepta/main/com/acme/rules/Offer.dmn")).content()
                .contains("hitPolicy=\"FIRST\"", "isCollection=\"true\"",
                        "<outputValues id=\"output_values_0\"><text>\"iberian\", \"senior\", \"standard\"</text></outputValues>");
    }

    @Test
    void a_dmn_table_is_named_after_its_decision() {
        extension.getTables().register("discount",
                table -> table.getSource().set(projectDir.resolve("src/main/rules/camunda-modeler-discount.dmn").toFile()));

        task().generate();

        Assertions.assertThat(projectDir.resolve("build/generated/sources/praecepta/java/main/com/acme/rules/Discount.java")).exists();
        Assertions.assertThat(projectDir.resolve("build/generated/resources/praecepta/main/com/acme/rules/Discount.dmn")).exists();
    }

    /** A DMN model whose decisions require one another (#14): a model class, and an input record and a class per decision. */
    @Test
    void a_decision_requirements_graph_generates_a_class_per_decision() {
        extension.getTables().register("credit", table -> table.getSource().set(projectDir.resolve("src/main/rules/credit.dmn").toFile()));

        task().generate();

        var sources = projectDir.resolve("build/generated/sources/praecepta/java/main/com/acme/rules");
        for (var name : List.of("CreditModel", "RiskCategory", "RiskCategoryInput", "CreditLimit", "CreditLimitInput", "MonthlyLimit",
                "MonthlyLimitInput")) {
            Assertions.assertThat(sources.resolve(name + ".java")).exists();
        }
        Assertions.assertThat(sources.resolve("MonthlyLimit.java")).content().contains("// Generated by praecepta-gradle-plugin from credit.dmn");
        Assertions.assertThat(projectDir.resolve("build/generated/resources/praecepta/main/com/acme/rules/CreditModel.dmn")).exists();
    }

    @Test
    void a_removed_table_leaves_no_generated_files() {
        fees("fees");
        task().generate();
        extension.getTables().clear();
        extension.getTables().register("discount",
                table -> table.getSource().set(projectDir.resolve("src/main/rules/camunda-modeler-discount.dmn").toFile()));

        task().generate();

        var sources = projectDir.resolve("build/generated/sources/praecepta/java/main/com/acme/rules");
        Assertions.assertThat(sources.resolve("Fees.java")).doesNotExist();
        Assertions.assertThat(sources.resolve("Discount.java")).exists();
    }

    @Test
    void skip_writes_nothing() {
        fees("fees");
        task().generate();
        extension.getSkip().set(true);

        task().generate();

        Assertions.assertThat(projectDir.resolve("build/generated/sources/praecepta/java/main/com/acme/rules/Fees.java")).doesNotExist();
    }

    @Test
    void two_tables_cannot_generate_the_same_class() {
        fees("fees");
        fees("more fees");

        Assertions.assertThatThrownBy(task()::generate)
                .isInstanceOf(GradleException.class)
                .hasMessage("Two tables generate the class Fees; set 'className' on one");
    }

    @Test
    void fail_on_controls_whether_validation_issues_fail_the_build() {
        extension.getTables().register("tiers", table -> {
            table.getSource().set(projectDir.resolve("src/main/rules/overlapping.csv").toFile());
            table.getClassName().set("Tier");
            table.getHitPolicy().set("UNIQUE");
            table.inputs(inputs -> inputs.column("country"));
            table.outputs(outputs -> outputs.column("tier"));
        });
        Assertions.assertThatThrownBy(task()::generate)
                .isInstanceOf(GradleException.class)
                .hasMessageContaining("overlap");

        extension.getFailOn().set("none"); // reported as warnings only
        task().generate();
        Assertions.assertThat(projectDir.resolve("build/generated/sources/praecepta/java/main/com/acme/rules/Tier.java")).exists();

        extension.getFailOn().set("SOMETIMES");
        Assertions.assertThatThrownBy(task()::generate)
                .isInstanceOf(GradleException.class)
                .hasMessage("'failOn' must be ERROR, WARNING or NONE, not SOMETIMES");
    }

    @Test
    void configuration_errors_become_build_failures_naming_the_gradle_settings() {
        Assertions.assertThatThrownBy(task()::generate)
                .isInstanceOf(GradleException.class)
                .hasMessageStartingWith("Register at least one table");

        extension.getTables().register("fees", table -> {
            table.getSource().set(projectDir.resolve("src/main/rules/fees.csv").toFile());
            table.inputs(inputs -> inputs.column("zone"));
            table.outputs(outputs -> outputs.column("fee", column -> column.getType().set("NUMBER")));
        });
        Assertions.assertThatThrownBy(task()::generate)
                .isInstanceOf(GradleException.class)
                .hasMessageEndingWith(": 'hitPolicy' is required for Excel and CSV tables");

        extension.getTables().getByName("fees").getHitPolicy().set("SOMETIMES");
        Assertions.assertThatThrownBy(task()::generate)
                .isInstanceOf(GradleException.class)
                .hasMessage("Table 'fees': 'hitPolicy' must be one of UNIQUE, ANY, PRIORITY, FIRST, OUTPUT_ORDER, RULE_ORDER, COLLECT,"
                        + " not SOMETIMES");

        extension.getTables().getByName("fees").getHitPolicy().set("COLLECT");
        extension.getTables().getByName("fees").getOutputs().getColumns().getFirst().getType().set("MONEY");
        Assertions.assertThatThrownBy(task()::generate)
                .isInstanceOf(GradleException.class)
                .hasMessageStartingWith("Table 'fees', column 'fee': 'type' must be one of STRING, NUMBER,");

        extension.getTables().register("missing", table -> table.getSource().set(projectDir.resolve("src/main/rules/missing.csv").toFile()));
        extension.getTables().getByName("fees").getOutputs().getColumns().getFirst().getType().set("NUMBER");
        Assertions.assertThatThrownBy(task()::generate)
                .isInstanceOf(GradleException.class)
                .hasMessageEndingWith("missing.csv does not exist");

        var fees = extension.getTables().getByName("fees");
        Assertions.assertThatThrownBy(() -> fees.inputs(inputs -> inputs.column(" ")))
                .isInstanceOf(InvalidUserDataException.class)
                .hasMessageStartingWith("Every column needs a name");
    }

    @Test
    void a_table_without_a_source_is_reported_by_the_compiler() {
        extension.getTables().register("fees");

        Assertions.assertThatThrownBy(task()::generate)
                .isInstanceOf(GradleException.class)
                .hasMessage("Every table needs a 'source'");
    }

    @Test
    void fails_on_errors_and_does_not_skip_by_default() {
        Assertions.assertThat(extension.getFailOn().get()).isEqualTo("ERROR");
        Assertions.assertThat(extension.getSkip().get()).isFalse();
    }

    // ---- helpers -------------------------------------------------------------------------------

    /** A COLLECT/SUM table over fees.csv, generating the class Fees. */
    private void fees(String name) {
        extension.getTables().register(name, table -> {
            table.getSource().set(projectDir.resolve("src/main/rules/fees.csv").toFile());
            table.getClassName().set("Fees");
            table.getHitPolicy().set("COLLECT");
            table.getAggregation().set("SUM");
            table.inputs(inputs -> inputs.column("zone"));
            table.outputs(outputs -> outputs.column("fee", column -> column.getType().set("NUMBER")));
        });
    }

    /** The files generated for one table, named as the compiler's golden files, as the Maven plugin names them. */
    private static Map<String, String> generated(Path generated, String packagePath, String className) throws IOException {
        var files = new TreeMap<String, String>();
        var sources = generated.resolve("sources/praecepta/java/main/" + packagePath);
        for (var name : List.of(className, className + "Input", className + "Output")) {
            files.put(name + ".java.txt", Files.readString(sources.resolve(name + ".java"), StandardCharsets.UTF_8)
                    .replace("praecepta-gradle-plugin", "praecepta-maven-plugin"));
        }
        files.put(className + ".dmn.txt", Files.readString(generated.resolve("resources/praecepta/main/" + packagePath + className + ".dmn"),
                StandardCharsets.UTF_8));
        return files;
    }

    /** praecepta-compiler's golden files, which pin the Maven plugin's output. */
    private static Map<String, String> golden(String table) throws IOException {
        var files = new TreeMap<String, String>();
        try (var stream = Files.list(Path.of("../praecepta-compiler/src/test/resources/golden", table))) {
            for (var file : stream.toList()) {
                files.put(file.getFileName().toString(), Files.readString(file, StandardCharsets.UTF_8));
            }
        }
        return files;
    }

    private GeneratePraecepta task() {
        return (GeneratePraecepta) project.getTasks().getByName(PraeceptaPlugin.TASK_NAME);
    }
}
